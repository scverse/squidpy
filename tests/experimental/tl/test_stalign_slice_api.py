def _points_sdata(n: int = 400) -> tuple[SpatialData, np.ndarray]:
    rng = np.random.default_rng(0)
    coords = np.column_stack([rng.normal(50.0, 12.0, n), rng.normal(-30.0, 9.0, n)])
    sdata = SpatialData(points={"cells": PointsModel.parse(pd.DataFrame({"x": coords[:, 0], "y": coords[:, 1]}))})
    return sdata, coords


def test_rasterize_points_conserves_mass() -> None:
    """Every point contributes exactly one unit, wherever it sits.

    This is the property that makes the raster a density rather than an approximation of
    one, and it is what a blur with plain zero padding silently breaks near the border.
    """
    sdata, coords = _points_sdata()
    image = rasterize_points(sdata, "cells", dx=3.0, blur=1.0)
    assert float(np.asarray(image).sum()) == pytest.approx(coords.shape[0], rel=1e-9)


def test_rasterize_points_makes_one_channel_per_blur() -> None:
    sdata, _ = _points_sdata()
    image = rasterize_points(sdata, "cells", dx=4.0, blur=(2.0, 1.0, 0.5))
    assert np.asarray(image).shape[0] == 3
    assert image.dims == ("c", "y", "x")


def test_rasterize_points_is_registered_where_the_points_are() -> None:
    """The raster has to land on the points, not at the origin.

    Mapping the image's own corner pixel through its transformation must reproduce the
    grid origin the rasteriser chose, which sits a margin below the points' minimum.
    """
    from spatialdata.transformations import get_transformation

    sdata, coords = _points_sdata()
    dx = 3.0
    image = rasterize_points(sdata, "cells", dx=dx, blur=1.0, expand=1.1)
    matrix = np.asarray(
        get_transformation(image, to_coordinate_system="global").to_affine_matrix(
            input_axes=("y", "x"), output_axes=("y", "x")
        )
    )

    origin = matrix @ np.array([0.0, 0.0, 1.0])
    span = np.ptp(coords, axis=0)
    centre = (coords.min(axis=0) + coords.max(axis=0)) / 2.0
    expected = centre - span * 1.1 / 2.0  # the rasteriser's own grid origin, in `(x, y)`

    np.testing.assert_allclose(origin[0], expected[1], atol=dx)
    np.testing.assert_allclose(origin[1], expected[0], atol=dx)
    np.testing.assert_allclose(np.diag(matrix)[:2], [dx, dx])


def test_rasterize_points_key_added_stores_the_image() -> None:
    sdata, _ = _points_sdata()
    assert rasterize_points(sdata, "cells", key_added="density", dx=4.0) is sdata.images["density"]


def test_rasterize_points_reports_a_missing_element() -> None:
    sdata, _ = _points_sdata()
    with pytest.raises(KeyError, match="no such points element"):
        rasterize_points(sdata, "nope")


def test_rasterize_points_needs_no_jax() -> None:
    """It is a plain image primitive, so the optional JAX extra must not gate it."""
    import subprocess
    import sys

    code = (
        "import sys; import squidpy.experimental.im as m; "
        "assert m.rasterize_points is not None; "
        "sys.exit(1 if 'jax' in sys.modules else 0)"
    )
    assert subprocess.run([sys.executable, "-c", code], check=False).returncode == 0
