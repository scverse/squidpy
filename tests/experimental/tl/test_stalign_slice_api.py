"""``align_stalign_slice`` and ``rasterize_points``, through their public entry points.

Container access and write-back only: the numerics are covered by ``test_stalign.py`` and
compared against the original STalign out of band, from the reference bundle generated by
https://github.com/theislab/squidpy-ports.
"""

from __future__ import annotations

import numpy as np
import pytest

pytest.importorskip("jax")
pytest.importorskip("spatialdata")

import anndata as ad  # noqa: E402
import pandas as pd  # noqa: E402
from spatialdata import SpatialData  # noqa: E402
from spatialdata.models import Image2DModel, Image3DModel, PointsModel  # noqa: E402
from spatialdata.transformations import Scale, Translation  # noqa: E402
from spatialdata.transformations import Sequence as TransformSequence  # noqa: E402

from squidpy.experimental.im import rasterize_points  # noqa: E402
from squidpy.experimental.tl import StalignSliceResult, align_stalign_slice  # noqa: E402

#: Rank-3 settings small enough to stay fast, large enough to run the whole path.
_TINY = {"a": 3.0, "expand": 1.25, "nt": 1, "niter": 1, "epV": 1.0}
_VOXEL = 2.0


def _volume(nz: int = 7, ny: int = 11, nx: int = 13) -> np.ndarray:
    zz, yy, xx = np.meshgrid(np.arange(nz), np.arange(ny), np.arange(nx), indexing="ij")
    blob = np.exp(-(((zz - nz / 2) / 2.0) ** 2 + ((yy - ny / 2) / 3.0) ** 2 + ((xx - nx / 2) / 3.5) ** 2))
    return np.stack([blob, (blob - blob.mean()) ** 2])


def _sdata(*, ref_translation: tuple[float, float, float] | None = None) -> SpatialData:
    volume = _volume()
    transformations = [Scale([_VOXEL, _VOXEL, _VOXEL], axes=("z", "y", "x"))]
    if ref_translation is not None:
        transformations.append(Translation(list(ref_translation), axes=("z", "y", "x")))
    sdata = SpatialData(
        images={
            "atlas": Image3DModel.parse(
                volume,
                dims=("c", "z", "y", "x"),
                transformations={"global": TransformSequence(transformations)},
            ),
            "section": Image2DModel.parse(
                volume[0, 3][None],
                dims=("c", "y", "x"),
                transformations={"global": Scale([_VOXEL, _VOXEL], axes=("y", "x"))},
            ),
        }
    )
    coords = np.column_stack([np.linspace(2.0, 20.0, 12), np.linspace(2.0, 16.0, 12)])
    table = ad.AnnData(np.zeros((12, 1)), obsm={"spatial": coords})
    sdata.tables["cells"] = table
    return sdata


def _fit(sdata: SpatialData, **kwargs):
    return align_stalign_slice(sdata, image_key=("atlas", "section"), **{**_TINY, **kwargs})


def test_returns_the_fit_when_nothing_is_written() -> None:
    result = _fit(_sdata())
    assert isinstance(result, StalignSliceResult)


def test_physical_axes_come_from_the_element_transformation() -> None:
    """The element's own scale supplies the units, so nothing has to be restated.

    A ``*_scale`` argument could disagree with the container; reading the transformation
    cannot.
    """
    result = _fit(_sdata())
    np.testing.assert_allclose(np.asarray(result.ref_axes[0]), np.arange(7) * _VOXEL)
    np.testing.assert_allclose(np.asarray(result.query_axes[0]), np.arange(11) * _VOXEL)


def test_element_translation_shifts_the_axes() -> None:
    """A translation on the element moves the frame the fit works in."""
    result = _fit(_sdata(ref_translation=(100.0, 10.0, 20.0)))
    np.testing.assert_allclose(np.asarray(result.ref_axes[0]), np.arange(7) * _VOXEL + 100.0)
    np.testing.assert_allclose(np.asarray(result.ref_axes[2]), np.arange(13) * _VOXEL + 20.0)


def test_rotation_in_the_transformation_is_refused() -> None:
    """Per-axis coordinates cannot express a rotation, so guessing would be wrong."""
    from spatialdata.transformations import Affine

    sdata = _sdata()
    rotation = np.eye(4)
    rotation[1:3, 1:3] = [[0.0, -1.0], [1.0, 0.0]]
    sdata.images["atlas"] = Image3DModel.parse(
        _volume(),
        dims=("c", "z", "y", "x"),
        transformations={"global": Affine(rotation, input_axes=("z", "y", "x"), output_axes=("z", "y", "x"))},
    )
    with pytest.raises(ValueError, match="rotation or shear"):
        _fit(sdata)


def test_write_back_adds_three_columns_to_a_copy() -> None:
    sdata = _sdata()
    out = _fit(sdata, table_key="cells", key_added="atlas_xyz")

    assert isinstance(out, SpatialData)
    assert out.tables["cells"].obsm["atlas_xyz"].shape == (12, 3)
    assert "atlas_xyz" not in sdata.tables["cells"].obsm, "inplace=False must not touch the input"


def test_write_back_inplace_returns_none() -> None:
    sdata = _sdata()
    assert _fit(sdata, table_key="cells", key_added="atlas_xyz", inplace=True) is None
    assert sdata.tables["cells"].obsm["atlas_xyz"].shape == (12, 3)


def test_key_added_needs_a_table_key() -> None:
    """Which table holds the cells is not inferable, and guessing wrong is silent."""
    with pytest.raises(ValueError, match="table_key"):
        _fit(_sdata(), key_added="atlas_xyz")


def test_inplace_without_key_added_is_refused() -> None:
    with pytest.raises(ValueError, match="nothing to write"):
        _fit(_sdata(), inplace=True)


def test_a_two_dimensional_reference_is_refused() -> None:
    """A ``(c, y, x)`` section as the reference reads as a one-voxel-deep volume.

    Left unguarded that fit "succeeds": the z axis has a single sample, so its spacing
    comes out as zero and every interpolated value is silently inf or nan. There is no
    out-of-plane information to fit either way -- ``align_stalign_image`` is the 2D path.
    """
    sdata = _sdata()
    sdata.images["flat"] = Image2DModel.parse(
        _volume()[0, 3][None],
        dims=("c", "y", "x"),
        transformations={"global": Scale([_VOXEL, _VOXEL], axes=("y", "x"))},
    )
    with pytest.raises(ValueError, match="at least two samples along `z`"):
        align_stalign_slice(sdata, image_key=("flat", "section"), **_TINY)


